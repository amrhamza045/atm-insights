export function resolvePackageMedia(pkg) {
  if (!pkg) return { image: "", video: "", gallery: [] };
  const gallery = Array.isArray(pkg.media_gallery) ? pkg.media_gallery.filter((m) => m?.url) : [];
  const firstGalleryImage = gallery.find((m) => m.type !== "video")?.url || "";
  const firstGalleryVideo = gallery.find((m) => m.type === "video")?.url || "";
  const name = String(pkg.name || "");
  const fallbackImage =
    PACKAGE_IMAGES[pkg.id] ||
    NAME_IMAGE_FALLBACKS.find(([re]) => re.test(name))?.[1] ||
    "";
  const fallbackVideo =
    PACKAGE_VIDEOS[pkg.id] ||
    NAME_VIDEO_FALLBACKS.find(([re]) => re.test(name))?.[1] ||
    "";

  const image = pkg.cover_image_url || firstGalleryImage || fallbackImage;
  const video = pkg.cover_video_url || firstGalleryVideo || fallbackVideo;

  return {
    image,
    video,
    gallery,
    hasCustomImage: Boolean(pkg.cover_image_url || firstGalleryImage),
    hasCustomVideo: Boolean(pkg.cover_video_url || firstGalleryVideo),
  };
}