export function canAccessCatalogItem(item, { isAdmin, permissions, currentUser }) {
  if (item.safetyValveOnly) {
    return currentUser?.perm_is_safety_valve === true;
  }
  if (item.adminOnly) {
    return !!isAdmin;
  }
  if (!item.requiredPermissions || item.requiredPermissions.length === 0) {
    return true;
  }
  if (isAdmin) return true;
  return item.requiredPermissions.some((k) => permissions?.[k] === true);
}